// Exportable report: Markdown, JSON and a self-contained print-friendly HTML page (Save as PDF).
import type { Finding, Severity } from './achilles-data'
import { cvssLabel, severityMeta } from './achilles-data'
import type { ScanResult } from './scan-types'
import { securityScoreOf, verdictOf } from './fixes'

const ORDER: Severity[] = ['critical', 'high', 'medium', 'low']
const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

function stamp(scan: ScanResult) {
  return (scan.finished_at ?? scan.created_at ?? new Date().toISOString()).slice(0, 10)
}

export function fileBase(scan: ScanResult) {
  return `achilles-${scan.target.host.replace(/[^a-z0-9.-]/gi, '_')}-${stamp(scan)}`
}

export function toMarkdown(scan: ScanResult, findings: Finding[]): string {
  const v = verdictOf(scan)
  const out: string[] = [
    `# Achilles security report: ${scan.target.host}`,
    '',
    `Scanned ${stamp(scan)} · grade **${scan.summary.grade}** · security score ${securityScoreOf(scan)}/100 · ${v.label}`,
    '',
    v.text,
    '',
  ]
  const cut = Object.entries(scan.tools).filter(([, t]) => ['timeout', 'error', 'not_installed'].includes(t.status))
  if (cut.length) {
    out.push('> Some checks were cut short: ' + cut.map(([n, t]) => `${n} (${t.message || t.status})`).join(', '), '')
  }
  if (scan.stack.technologies.length) out.push(`Stack detected: ${scan.stack.technologies.join(', ')}`, '')
  for (const sev of ORDER) {
    const list = findings.filter((f) => f.severity === sev)
    if (!list.length) continue
    out.push(`## ${severityMeta[sev].label} (${list.length})`, '')
    for (const f of list) {
      out.push(
        `### ${f.title}`,
        `- Where: \`${f.location}\``,
        ...(cvssLabel(f.raw) ? [`- ${cvssLabel(f.raw)}`] : []),
        `- What's wrong: ${f.summary}`,
        `- Why it matters: ${f.impact}`,
        '',
        '**Fix prompt (paste into your AI builder):**',
        '',
        ...f.fixPrompt.split('\n').map((l) => `> ${l}`),
        '',
      )
    }
  }
  if (!findings.length) out.push('No weaknesses were found by these checks.', '')
  out.push('---', 'Generated by ACHILLES. Only findings produced by the scanning tools are listed.')
  return out.join('\n')
}

export function toHtml(scan: ScanResult, findings: Finding[]): string {
  const v = verdictOf(scan)
  const color: Record<Severity, string> = { critical: '#b42318', high: '#c4410a', medium: '#9a5b06', low: '#1d6fa8' }
  const sections = ORDER.map((sev) => {
    const list = findings.filter((f) => f.severity === sev)
    if (!list.length) return ''
    return `<h2 style="color:${color[sev]}">${severityMeta[sev].label} <small>(${list.length})</small></h2>${list
      .map(
        (f) => `<article><h3>${esc(f.title)}</h3>
<p class="loc">${esc(f.location)}${cvssLabel(f.raw) ? `<br>${esc(cvssLabel(f.raw)!)}` : ''}</p>
<p><b>What’s wrong.</b> ${esc(f.summary)}</p>
<p><b>Why it matters.</b> ${esc(f.impact)}</p>
<p class="prompt"><b>Fix prompt</b><br>${esc(f.fixPrompt)}</p></article>`,
      )
      .join('')}`
  }).join('')
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${esc(fileBase(scan))}</title>
<style>
body{font:15px/1.55 system-ui,sans-serif;max-width:780px;margin:32px auto;padding:0 20px;color:#1b1a17}
h1{margin-bottom:4px;color:#173b56} h2{margin-top:34px;border-bottom:1px solid #ddd;padding-bottom:6px}
h3{margin:0 0 4px} small{font-weight:400;color:#777} .meta{color:#666} .loc{font:12px ui-monospace,monospace;color:#666;margin:0 0 8px}
article{border:1px solid #e3e0d8;border-radius:8px;padding:14px 16px;margin:12px 0;break-inside:avoid}
.prompt{background:#eff7fa;border-left:3px solid #287eb0;padding:10px 12px;border-radius:4px}
.badge{display:inline-block;font-weight:700;font-size:28px;border:2px solid #1b1a17;border-radius:8px;padding:0 14px;margin-right:10px}
@media print{body{margin:0}}
</style></head><body>
<h1>Achilles security report</h1>
<p class="meta">${esc(scan.target.host)} · ${stamp(scan)}</p>
<p><span class="badge">${scan.summary.grade}</span><b>${esc(v.label)}</b>: ${esc(v.text)} (security score ${securityScoreOf(scan)}/100)</p>
${scan.stack.technologies.length ? `<p class="meta">Stack detected: ${esc(scan.stack.technologies.join(', '))}</p>` : ''}
${sections || '<p>No weaknesses were found by these checks.</p>'}
<p class="meta" style="margin-top:36px">Generated by ACHILLES. Only findings produced by the scanning tools are listed.</p>
</body></html>`
}

export function downloadText(filename: string, content: string, mime: string) {
  const url = URL.createObjectURL(new Blob([content], { type: mime }))
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

/** Opens the print-friendly report and triggers the browser's print dialog (choose "Save as PDF"). */
export function printReport(scan: ScanResult, findings: Finding[]) {
  const w = window.open('', '_blank')
  if (!w) {
    downloadText(`${fileBase(scan)}.html`, toHtml(scan, findings), 'text/html')
    return
  }
  w.document.open()
  w.document.write(toHtml(scan, findings))
  w.document.close()
  w.focus()
  setTimeout(() => w.print(), 300)
}
